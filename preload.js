const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('whatsapx', {
  pronta: () => ipcRenderer.send('ui-pronta'),
  addConta: () => ipcRenderer.send('add-conta'),
  selectConta: (id) => ipcRenderer.send('select-conta', id),
  menuConta: (id) => ipcRenderer.send('menu-conta', id),
  renameConta: (id, nome) => ipcRenderer.send('rename-conta', { id, nome }),
  abrirSnippets: () => ipcRenderer.send('abrir-snippets'),
  waSecao: (s) => ipcRenderer.send('wa-secao', s),
  abrirBerry: () => ipcRenderer.send('abrir-berry'),
  getBerryConfig: () => ipcRenderer.invoke('get-berry-config'),
  berryToken: (forcar) => ipcRenderer.invoke('berry-token', !!forcar),
  berryLoginStatus: () => ipcRenderer.invoke('berry-login-status'),
  berryLoginSalvar: (email, senha) => ipcRenderer.invoke('berry-login-salvar', { email, senha }),
  berryLoginSair: () => ipcRenderer.invoke('berry-login-sair'),
  onBerryPreset: (cb) => ipcRenderer.on('berry-preset', (_e, p) => cb(p)),
  lerChatAberto: () => ipcRenderer.invoke('ler-chat-aberto'),
  enviarAvisos: (itens) => ipcRenderer.invoke('enviar-avisos', itens),
  onEnvioProgresso: (cb) => ipcRenderer.on('envio-progresso', (_e, r) => cb(r)),
  iniciarAvisoGeral: (dados) => ipcRenderer.invoke('aviso-geral-iniciar', dados),
  controleAvisoGeral: (acao) => ipcRenderer.send('aviso-geral-controle', acao),
  getAvisoGeralEstado: () => ipcRenderer.invoke('aviso-geral-estado'),
  onAvisoProgresso: (cb) => ipcRenderer.on('aviso-progresso', (_e, ev) => cb(ev)),
  botEstado: () => ipcRenderer.invoke('bot-estado'),
  botSalvar: (cfgBot) => ipcRenderer.invoke('bot-salvar', cfgBot),
  botGrupos: (contaId) => ipcRenderer.invoke('bot-grupos', contaId),
  botContatos: (contaId) => ipcRenderer.invoke('bot-contatos', contaId),
  botVincularIds: () => ipcRenderer.invoke('bot-vincular-ids'),
  botTestar: (texto) => ipcRenderer.invoke('bot-testar', texto),
  botLiberarNumero: (n) => ipcRenderer.invoke('bot-liberar-numero', n),
  botSemanalAgora: () => ipcRenderer.invoke('bot-semanal-agora'),
  botSaudeAgora: (opcoes) => ipcRenderer.invoke('bot-saude-agora', opcoes),
  berryInserir: (texto) => ipcRenderer.send('berry-inserir', texto),
  getSnippets: () => ipcRenderer.invoke('get-snippets'),
  saveSnippets: (lista) => ipcRenderer.send('save-snippets', lista),
  onContas: (cb) => ipcRenderer.on('contas', (_e, d) => cb(d)),
  onBadges: (cb) => ipcRenderer.on('badges', (_e, d) => cb(d)),
  onTheme: (cb) => ipcRenderer.on('ui-theme', (_e, t) => cb(t)),
  setTema: (t) => ipcRenderer.send('set-tema', t),
  getTema: () => ipcRenderer.invoke('get-tema'),
  menuReacao: () => ipcRenderer.send('menu-reacao'),
  getReacao: () => ipcRenderer.invoke('get-reacao'),
  onReacao: (cb) => ipcRenderer.on('reacao-atual', (_e, r) => cb(r)),
  onTemaEscolha: (cb) => ipcRenderer.on('tema-escolha', (_e, t) => cb(t)),
  onPedirRename: (cb) => ipcRenderer.on('pedir-rename', (_e, id) => cb(id)),
});
